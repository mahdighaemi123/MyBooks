# At the start of the adventure, we have 10 coins
gold_coins = 10
print("Current gold coins:")
print(gold_coins)

# We defeat a giant and get 20 new coins
# We replace the old content of the box with the new value
gold_coins = 20
print("Gold coins after defeating the giant:")
print(gold_coins)

# We can even do calculations on the box itself
# We spend 5 coins
gold_coins = gold_coins - 5
print("Remaining gold coins:")
print(gold_coins) # Output will be 15