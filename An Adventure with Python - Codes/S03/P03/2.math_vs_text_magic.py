# The magic of math (adding numbers)
num1 = 20
num2 = 5
result_math = num1 + num2
print("Result of math magic:")
print(result_math) # Output: 25
 
# The magic of text (concatenating strings)
text1 = "20" # This is a string, not a number
text2 = "5"  # This is also a string
result_text = text1 + text2
print("Result of text magic:")
print(result_text) # Output: "205"