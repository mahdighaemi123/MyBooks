shopping_list = ["sword", "health_potion", "bread"]
 
# Access items by their index number
first_item = shopping_list[0] #
second_item = shopping_list[1]
 
print("First item needed:")
print(first_item) # Output: sword
print("Second item needed:")
print(second_item) # Output: health_potion
 
# What about the LAST item?
# You can use -1 to get the last item, -2 for the second-to-last, etc.
last_item = shopping_list[-1] #
print("Last item:")
print(last_item) # Output: bread