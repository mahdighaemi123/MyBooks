# We use curly braces {} for dictionaries
# We use colons (:) to link a KEY to a VALUE
adventurer_stats = {
    "name": "Kael",
    "level": 5,
    "class": "Mage",
    "gold": 150
}

# Accessing data using the 'key'
print("Adventurer's Name:")
print(adventurer_stats["name"])  # Output: Kael

print("Current Level:")
print(adventurer_stats["level"]) # Output: 5