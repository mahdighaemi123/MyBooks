class Potion:
    pass

# 3. Adding Data Manually
red_potion = Potion()
blue_potion = Potion()
 
# Let's give them distinct features
# We open 'red_potion' and put "Red" in a variable called 'color'
red_potion.color = "Red"
red_potion.price = 50
 
# We open 'blue_potion' and put "Blue" in a variable called 'color'
blue_potion.color = "Blue"
blue_potion.price = 100
 
print(red_potion.color)  # Output: Red
print(blue_potion.price) # Output: 100